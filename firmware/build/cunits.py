#!/usr/bin/env python3
"""Compile OType's three C units for the ColdFire into assembly (build/out/*.s).

    python3 build/cunits.py [--out DIR]

    otype_c.s       c/otype_unit.c   the bytecode VM (+ the PRNG probe)
    otype_comp.s    c/otc_comp.c     the compiler that runs on the unit (-DOTC_NO_DUMP: the test dump is left out)
    otype_script.s  c/otc_script.c   the /SCRIPTS loader

Flags: -mcfv4e -Os -ffreestanding -fno-builtin -nostdlib -Wall -Wextra -Werror -Wstack-usage=256. The assembly is
post-processed and checked against the unit policy: `.rodata` goes to `.text`, any `.data` / `.bss` / `.comm` / other
section is refused (the runtime is one flat binary), and the object may reference only the `otb_host_*` imports its
unit is allowed (so no memcpy, __mulsi3, ...). Each result is assembled with -mcpu=5407, the strictest ColdFire assembly
mode a host tool is likely to use: gcc's -mcfv4e output may use an index scale of 8 that -mcpu=5475 accepts and 5407 refuses.
"""
import argparse
import pathlib
import re
import subprocess
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
FW = HERE.parent
C_DIR = FW / "c"
CFLAGS = ["-mcfv4e", "-Os", "-ffreestanding", "-fno-builtin", "-fno-common",
          "-fomit-frame-pointer", "-fno-asynchronous-unwind-tables", "-fno-unwind-tables",
          "-fno-stack-protector", "-nostdlib", "-Wall", "-Wextra", "-Werror",
          "-Wstack-usage=256"]
BAD = re.compile(r"^\s*\.(data|bss|comm|lcomm)\b")
SECTION = re.compile(r"^\s*\.section\s+(\S+)")

# host imports of the VM unit: implemented in src/bridge.S, src/card.S (asm on the unit); the nine audio ones come
# from the integrating firmware, else from the weak defaults of c/audio_default.c (-DOTYPE_AUDIO_DEFAULTS)
VM_IMPORTS = {"otb_host_add", "otb_host_dir_open", "otb_host_dir_next", "otb_host_dir_skipped",
              "otb_host_slot_name", "otb_host_slot_set", "otb_host_slot_load", "otb_host_slot_clr",
              "otb_host_card_busy", "otb_host_param_info", "otb_host_param_value",
              "otb_host_par_set", "otb_host_param_default", "otb_host_lfo_set", "otb_host_lfo_waves",
              "otb_host_fx_count", "otb_host_fx_default", "otb_host_fx_set", "otb_host_scene_put",
              "otb_host_trk_slot_init", "otb_host_trk_slot", "otb_host_tempo",
              "otb_host_audio_input", "otb_host_src_save", "otb_host_flex_load", "otb_host_flex_free", "otb_host_flex_del",
              "otb_host_cat_clr", "otb_host_cat_add", "otb_host_cat_save", "otb_host_norm"}
# (output file, source, extra -D, allowed undefined symbols, the global text symbol that must exist)
UNITS = [("otype_c.s", "otype_unit.c", ["OTYPE_AUDIO_DEFAULTS"], VM_IMPORTS, "otc_probe"),
         ("otype_comp.s", "otc_comp.c", ["OTC_NO_DUMP"], set(), "otc_compile"),
         ("otype_script.s", "otc_script.c", [],
          {"otb_host_ls_open", "otb_host_ls_next", "otb_host_file_read", "otb_host_compile"}, "ots_load")]


def run(cmd):
    r = subprocess.run([str(c) for c in cmd], stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
    if r.returncode:
        sys.exit(f"cunits: {cmd[0]} failed:\n{r.stdout}{r.stderr}")
    return r.stdout


def build_unit(out_path, src, defines, allowed, required):
    raw = run(["m68k-elf-gcc", *CFLAGS, f"-I{C_DIR}", *[f"-D{d}" for d in defines], "-S", "-o", "-", C_DIR / src])
    lines = [f"| GENERATED by build/cunits.py from c/{src} -- do not edit"]
    for line in raw.splitlines():
        if BAD.match(line):
            sys.exit(f"cunits: refused: {line.strip()!r} (no .data/.bss/.comm in a unit)")
        m = SECTION.match(line)
        if m:
            if not m.group(1).startswith(".rodata"):
                sys.exit(f"cunits: refused: section {m.group(1)} (only .text/.rodata allowed)")
            line = "        .text"
        lines.append(line)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines) + "\n")
    with tempfile.TemporaryDirectory() as d:
        o = pathlib.Path(d) / "c.o"
        run(["m68k-elf-as", "-mcpu=5407", "-o", o, out_path])
        nm = run(["m68k-elf-nm", o]).splitlines()
        size = run(["m68k-elf-size", "-A", o])
    undef = {l.split()[-1] for l in nm if l.split()[0] == "U"}
    glob = {l.split()[-1] for l in nm if len(l.split()) == 3 and l.split()[1] == "T"}
    sec = {l.split()[0]: int(l.split()[1]) for l in size.splitlines() if l.startswith(".")}
    problems = []
    if undef - allowed:
        problems.append(f"undefined symbols {sorted(undef - allowed)}")
    if required not in glob:
        problems.append(f"{required} is not a global text symbol")
    if any(v and k not in (".text", ".comment") for k, v in sec.items()):
        problems.append(f"non-text sections {sec}")
    if problems:
        out_path.unlink()
        sys.exit(f"cunits: {out_path.name} refused: " + "; ".join(problems))
    print(f"cunits: wrote {out_path.name}: .text {sec.get('.text', 0)} B; exports {sorted(glob)}; imports {sorted(undef)}")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", type=pathlib.Path, default=HERE / "out")
    a = ap.parse_args()
    for name, src, defines, allowed, required in UNITS:
        build_unit(a.out / name, src, defines, allowed, required)


if __name__ == "__main__":
    main()
