#!/usr/bin/env python3
"""Generate build/out/otype.s: the assembly part of the OType module (linked with the three C units by build/link.py).

    python3 build/units.py [--out PATH]

The unit is, in this order: the header equates (layout.py's OT_* buffers as offsets from the symbol `otype_rgn` that
the link defines for the module's memory block, OT_ROW = 0, OT_JOB = 0x45) + src/stock.inc +
src/shim.S + the SCRIPT row's tables + src/{bridge,run,card,script,auto}.S concatenated as they are + `.weak` for
the symbols of the three C units (cunits.py builds them; link.py links all four).

A trial assembly (m68k-elf-as -mcpu=5407, linked at a made-up base with a made-up address for `otype_rgn`) checks that
the unit assembles and that every symbol the entry point and an interface need is defined. No address of the block
is known or assumed here: the integrating tool reserves it and the link resolves every OT_* equate.
"""
import argparse
import pathlib
import subprocess
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
FW = HERE.parent
SRC = FW / "src"
sys.path.insert(0, str(HERE))
import layout as L          # noqa: E402

TRIAL_BASE = 0x40a955e0     # a DRAM address: a trial link only
TRIAL_REGION = 0x41300000   # a made-up address for the region symbol: a trial link only
OT_ROW = 0
OT_JOB = 0x45
NAME_W, ACT_W = 6, 10       # the row label: NAME__ ' ' '<' ACTION____ '>' (src/shim.S .Lrelabel)
LABEL_LEN = NAME_W + 1 + 1 + ACT_W + 1
MAX_MENU_ACTIONS = 32 * 64  # 32 categories x 64 scripts (c/otc_script.c OTS_MAXACT)
SOURCES = ("bridge.S", "run.S", "card.S", "script.S", "auto.S")
# what the unit calls in the three C units
C_SYMBOLS = ("otb_host_commit", "otc_probe", "otc_vm_load", "otc_vm_bind", "otc_vm_bind_work", "otc_vm_run", "otc_vm_touched",
             "otc_vm_slots_touched", "otc_vm_part_touched", "otc_vm_fn_page", "otc_vm_fn_param", "otc_vm_fn_confirm",
             "otc_vm_set_params", "otc_vm_set_param_folder", "otc_compile", "ots_load")
# defined by the unit, needed by the entry point (README.md), by an interface and by the glue
NEED = ("otype_st", "otype_ot_stjob", "otype_ot_job", "otype_ot_load", "otype_ot_menu", "otype_ot_auto",
        "otype_probe", "otype_run", "otb_host_add", "otb_host_compile", "ot_ctx", "pop_rows")


def header():
    sym = L.REGION_SYMBOL
    h = ["| OType module (DRAM unit). GENERATED by build/units.py -- do not edit.",
         "| The buffers are offsets from " + sym + ", the symbol the link defines for the module's memory block.",
         "        .equ OTYPE, 1"]
    h += [f"        .equ OT_{k}, {sym} + 0x{v:x}" for k, v in L.OT_AT.items()]
    # the same offsets as plain numbers: the assembler cannot subtract two addresses that are both relative to a symbol
    # the link defines, so a length between two buffers is written with these (src/script.S)
    h += [f"        .equ OT_{k}_OFF, 0x{v:x}" for k, v in L.OT_AT.items()]
    h += [f"        .equ OT_ARENA_SIZE, {L.OT_ARENA_SIZE}", f"        .equ OT_STACK_TOP, {sym} + 0x{L.OT_STACK_TOP:x}",
          f"        .equ OT_REPORT_CAP, {L.OT_REPORT_CAP}", f"        .equ OT_SRC_CAP, {L.OT_SRC_CAP}",
          f"        .equ OT_ROW, {OT_ROW}", f"        .equ OT_JOB, 0x{OT_JOB:02x}"]
    return "\n".join(h) + "\n"


def row_tables():
    """The SCRIPT row (row OT_ROW = 0) and its action array: LOAD is action 0, the rest of the array
    (1 + MAX_MENU_ACTIONS records of 16 B) is filled at load time."""
    label = "SCRIPT".ljust(NAME_W) + " " + " " + "LOAD".ljust(ACT_W) + " "
    assert len(label) == LABEL_LEN
    cap = 1 + MAX_MENU_ACTIONS
    return "\n".join([
        "", "| ---- the SCRIPT row (generated by build/units.py) ----",
        f"        .equ    NAME_W, {NAME_W}", f"        .equ    ACT_W, {ACT_W}",
        "        .balign 4", "pop_rows:",
        f"        .long   pop_lb_{OT_ROW}, pop_acts_{OT_ROW}", "        .byte   1, 0, 0, 0",
        f"pop_acts_{OT_ROW}:",
        "        .long   otype_ot_load, pop_s_load, 0", "        .byte   0, 0, 0, 0",
        f"        .space  {(cap - 1) * 16}",
        "pop_s_load:", '        .asciz  "LOAD"',
        f"pop_lb_{OT_ROW}:", f'        .asciz  "{label}"', "        .balign 4", ""])


def run(cmd):
    r = subprocess.run([str(c) for c in cmd], stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
    if r.returncode:
        sys.exit(f"units: {cmd[0]} failed:\n{r.stdout}{r.stderr}")
    return r.stdout


def trial(unit):
    """Assemble and link at TRIAL_BASE; return (size, {symbol: address}) of the global text symbols."""
    with tempfile.TemporaryDirectory() as d:
        d = pathlib.Path(d)
        (d / "a.s").write_text(unit)
        run(["m68k-elf-as", "-mcpu=5407", "-o", d / "a.o", d / "a.s"])
        run(["m68k-elf-ld", f"-Ttext=0x{TRIAL_BASE:x}", f"--defsym={L.REGION_SYMBOL}=0x{TRIAL_REGION:x}", "-e", "0", "--no-warn-rwx-segments", "-o", d / "a.elf", d / "a.o"])
        run(["m68k-elf-objcopy", "-O", "binary", d / "a.elf", d / "a.bin"])
        syms = {}
        for line in run(["m68k-elf-nm", d / "a.elf"]).splitlines():
            parts = line.split()
            if len(parts) == 3 and parts[1] in "Tt":
                syms[parts[2]] = int(parts[0], 16)
        return len((d / "a.bin").read_bytes()), syms


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", type=pathlib.Path, default=HERE / "out" / "otype.s")
    a = ap.parse_args()
    unit = header() + (SRC / "stock.inc").read_text() + "\n" + (SRC / "shim.S").read_text() + row_tables()
    for part in SOURCES:
        unit += "\n" + (SRC / part).read_text()
    unit += "\n" + "".join(f"        .weak   {s}\n" for s in C_SYMBOLS)
    size, syms = trial(unit)
    missing = [k for k in NEED if k not in syms]
    if missing:
        sys.exit(f"units: symbols missing from the unit: {missing}")
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text(unit)
    print(f"units: wrote {a.out.name}: {len(unit.splitlines())} lines; a trial link at 0x{TRIAL_BASE:08x} is {size:,} B; "
          f"{len(NEED)} required symbols present")
    print(f"units: region {L.REGION_SYMBOL} {L.REGION_BYTES:,} B (the integrating tool reserves it; OT_VM = {L.REGION_SYMBOL} + 0x{L.OT_AT['VM']:x})")


if __name__ == "__main__":
    main()
