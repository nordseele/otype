#!/usr/bin/env python3
"""Compile OType's C (firmware/c/otype_unit.c = probe.c + vm.c) into an assembly unit for the firmware.

    python3 modules/otype/build_c.py [--sabotage] [--out PATH] [--host LIB.dylib]

Default output: firmware/build/out/otype_c.s. gcc -S for ColdFire V4e, then the asm is
post-processed and checked against the unit policy: .rodata goes to .text,
any .data/.bss/.comm/.lcomm/other section is refused (the runtime is one
flat binary), and the object may only reference the `otb_host_*` imports of
ALLOWED_UNDEF (so no memcpy, __mulsi3, ...). `otc_probe` must be a global text symbol.
--sabotage builds the deliberately wrong PRNG / MOD (must-fail check; also for --host).
--host builds the same C as a shared library for the Mac (host_shim.c).
"""
import argparse, pathlib, re, subprocess, sys, tempfile

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[1]
C_DIR = ROOT / "firmware" / "c"
SRC = C_DIR / "otype_unit.c"      # the ONE translation unit: probe.c + vm.c
INC = C_DIR
SHIM = C_DIR / "host_shim.c"
# the card / slot imports (declared in c/otc_vm.h; asm the on-unit card implementation on the unit, host_shim.c on the Mac)
ALLOWED_UNDEF = {"otb_host_add", "otb_host_dir_open", "otb_host_dir_next", "otb_host_dir_skipped",
                 "otb_host_slot_name", "otb_host_slot_set", "otb_host_slot_load", "otb_host_slot_clr",
                 "otb_host_card_busy",
                 "otb_host_param_info", "otb_host_param_value",      # the part's descriptor / value (c/otc_vm.h)
                 "otb_host_par_set", "otb_host_param_default", "otb_host_lfo_set", "otb_host_lfo_waves",
                 "otb_host_fx_count", "otb_host_fx_default", "otb_host_fx_set", "otb_host_scene_put",
                 "otb_host_trk_slot_init", "otb_host_trk_slot", "otb_host_tempo",     # the part writes / tempo (c/otc_vm.h)
                 "otb_host_audio_input", "otb_host_src_save", "otb_host_flex_load", "otb_host_flex_free", "otb_host_flex_del",
                 "otb_host_cat_clr", "otb_host_cat_add", "otb_host_cat_save", "otb_host_norm"}  # audio
CFLAGS = ["-mcfv4e", "-Os", "-ffreestanding", "-fno-builtin", "-fno-common",
          "-fomit-frame-pointer", "-fno-asynchronous-unwind-tables", "-fno-unwind-tables",
          "-fno-stack-protector", "-nostdlib", "-Wall", "-Wextra", "-Werror",
          "-Wstack-usage=256"]
BAD = re.compile(r"^\s*\.(data|bss|comm|lcomm)\b")
SECTION = re.compile(r"^\s*\.section\s+(\S+)")


def run(cmd, **kw):
    r = subprocess.run(cmd, capture_output=True, text=True, **kw)
    if r.returncode:
        sys.exit(f"build_c: {' '.join(map(str, cmd[:2]))} failed:\n{r.stdout}{r.stderr}")
    return r.stdout


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--sabotage", action="store_true")
    ap.add_argument("--out", type=pathlib.Path, default=ROOT / "firmware" / "build" / "out" / "otype_c.s")
    ap.add_argument("--host", type=pathlib.Path)
    ap.add_argument("--define", action="append", default=[], metavar="NAME[=V]",
                    help="extra -D for the must-fail builds (OTC_SABOTAGE_SORT ...); never for a real build")
    a = ap.parse_args()
    cmd = ["m68k-elf-gcc", *CFLAGS, f"-I{INC}"] + (["-DOTC_SABOTAGE"] if a.sabotage else []) \
        + [f"-D{d}" for d in a.define] + ["-S", "-o", "-", str(SRC)]
    raw = run(cmd)
    out = ["| GENERATED by modules/otype/build_c.py from firmware/c/probe.c — do not edit",
           "| (gcc -mcfv4e -Os; linked next to the firmware unit; policy in probe.c / vm.c)"]
    for line in raw.splitlines():
        if BAD.match(line):
            sys.exit(f"build_c: refused: {line.strip()!r} (no .data/.bss/.comm in the unit)")
        m = SECTION.match(line)
        if m:
            if m.group(1).startswith(".rodata"):
                line = "        .text"
            else:
                sys.exit(f"build_c: refused: section {m.group(1)} (only .text/.rodata allowed)")
        out.append(line)
    text = "\n".join(out) + "\n"
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text(text)
    with tempfile.TemporaryDirectory() as d:
        o = pathlib.Path(d) / "c.o"
        run(["m68k-elf-as", "-mcpu=5407", "-o", str(o), str(a.out)])
        nm = run(["m68k-elf-nm", str(o)]).splitlines()
        size = run(["m68k-elf-size", "-A", str(o)])
    undef = {l.split()[-1] for l in nm if l.split()[0] == "U"}
    bad = undef - ALLOWED_UNDEF
    glob = {l.split()[-1] for l in nm if len(l.split()) == 3 and l.split()[1] == "T"}
    if bad:
        a.out.unlink()
        sys.exit(f"build_c: refused: undefined symbols {sorted(bad)} (only {sorted(ALLOWED_UNDEF)})")
    if "otc_probe" not in glob:
        a.out.unlink()
        sys.exit("build_c: otc_probe is not a global T symbol")
    sec = {l.split()[0]: int(l.split()[1]) for l in size.splitlines() if l.startswith(".")}
    if any(v and k not in (".text", ".comment") for k, v in sec.items()):
        a.out.unlink()
        sys.exit(f"build_c: refused: non-text sections in the object {sec}")
    print(f"wrote {a.out}: .text {sec.get('.text', 0)} B; exports {sorted(glob)}; "
          f"imports {sorted(undef)}" + (" [SABOTAGED]" if a.sabotage else ""))
    if a.host:
        a.host.parent.mkdir(parents=True, exist_ok=True)
        run(["cc", "-O2", "-shared", "-fPIC", f"-I{INC}", *(["-DOTC_SABOTAGE"] if a.sabotage else []), *[f"-D{d}" for d in a.define],
             "-o", str(a.host), str(SRC), str(SHIM)])
        print(f"wrote {a.host}")


if __name__ == "__main__":
    main()
